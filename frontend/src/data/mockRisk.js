/** Independent 30-day series for Kenya — never a blended index */
export const KENYA_TRENDS = Array.from({ length: 30 }, (_, i) => {
  const day = i + 1;
  const rainfall = 4 + i * 0.55 + (i > 20 ? (i - 20) * 0.8 : 0);
  const floodScore = Math.min(100, 12 + rainfall * 1.7);
  const quakeScore = 16 + Math.sin(i / 4) * 4;
  return {
    day,
    label: `Aug ${day}`,
    rainfall: Number(rainfall.toFixed(1)),
    floodScore: Number(floodScore.toFixed(1)),
    quakeScore: Number(quakeScore.toFixed(1)),
  };
});
